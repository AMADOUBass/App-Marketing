import type { IncomingMessage } from 'node:http';
import type { Params } from 'nestjs-pino';
import type { DestinationStream } from 'pino';
import type { Options } from 'pino-http';
import { isHealthPath } from '../common/paths.js';
import type { Env } from './env.js';

/** Request/response fields that may carry credentials. Never written to logs. */
export const REDACTED_PATHS = [
  'req.headers.authorization',
  'req.headers.cookie',
  'req.headers["proxy-authorization"]',
  'req.headers["x-api-key"]',
  'res.headers["set-cookie"]',
];

function stripQuery(url: string): string {
  return url.split('?')[0] ?? url;
}

// The logging middleware may see a rewritten `url`; `originalUrl` keeps the full path.
function requestPath(req: IncomingMessage): string {
  return stripQuery(
    (req as IncomingMessage & { originalUrl?: string }).originalUrl ?? req.url ?? '',
  );
}

interface SerializedRequest {
  id: unknown;
  method: string;
  url: string;
}

/**
 * Request ids are generated by Fastify (see common/request-id.ts); pino-http reuses `req.id`.
 *
 * Request logs are an allow-list: id, method and path only. No query string (OAuth codes,
 * signed-URL tokens), no headers, no IP address (personal data).
 */
export function createLoggerParams(env: Env, stream?: DestinationStream): Params {
  const options: Options = {
    level: env.LOG_LEVEL,
    serializers: {
      req: (req: SerializedRequest) => ({
        id: req.id,
        method: req.method,
        url: stripQuery(req.url),
      }),
      res: (res: { statusCode: number }) => ({ statusCode: res.statusCode }),
    },
    // Defense in depth if a request object is ever logged by other means.
    redact: { paths: REDACTED_PATHS, censor: '[REDACTED]' },
    // Health probes run every few seconds; logging them only adds noise.
    autoLogging: { ignore: (req) => isHealthPath(requestPath(req)) },
    ...(env.LOG_PRETTY && !stream
      ? { transport: { target: 'pino-pretty', options: { singleLine: true } } }
      : {}),
  };

  return { pinoHttp: stream ? [options, stream] : options };
}
